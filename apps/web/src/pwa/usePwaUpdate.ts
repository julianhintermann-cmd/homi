import { useEffect, useRef } from 'react';
import { useRegisterSW } from 'virtual:pwa-register/react';

/** How often an open app checks for a new deployment. */
const UPDATE_CHECK_INTERVAL_MS = 60 * 60 * 1000;

export interface PwaUpdateState {
  /** A new version is installed and waiting (`registerType: 'prompt'`). */
  updateAvailable: boolean;
  /** The app shell is cached and works offline (first install). */
  offlineReady: boolean;
  /** Activates the waiting service worker and reloads the page. */
  applyUpdate: () => Promise<void>;
  dismissUpdate: () => void;
  dismissOfflineReady: () => void;
}

/**
 * Registers the service worker (generated by vite-plugin-pwa) and exposes the
 * "Update verfügbar" prompt state. Mount once (see `PwaUpdatePrompt`).
 */
export function usePwaUpdate(): PwaUpdateState {
  const registrationRef = useRef<ServiceWorkerRegistration | null>(null);
  const {
    needRefresh: [needRefresh, setNeedRefresh],
    offlineReady: [offlineReady, setOfflineReady],
    updateServiceWorker,
  } = useRegisterSW({
    immediate: true,
    onRegisteredSW(_swUrl, registration) {
      registrationRef.current = registration ?? null;
    },
    onRegisterError(error: unknown) {
      console.warn('[Homi] Service worker registration failed', error);
    },
  });

  useEffect(() => {
    const check = (): void => {
      const registration = registrationRef.current;
      if (!registration || !navigator.onLine || registration.installing) return;
      registration.update().catch(() => undefined);
    };
    const interval = window.setInterval(check, UPDATE_CHECK_INTERVAL_MS);
    const onVisible = (): void => {
      if (document.visibilityState === 'visible') check();
    };
    document.addEventListener('visibilitychange', onVisible);
    return () => {
      window.clearInterval(interval);
      document.removeEventListener('visibilitychange', onVisible);
    };
  }, []);

  return {
    updateAvailable: needRefresh,
    offlineReady,
    applyUpdate: () => updateServiceWorker(true),
    dismissUpdate: () => setNeedRefresh(false),
    dismissOfflineReady: () => setOfflineReady(false),
  };
}
